 * терминалът целия екран; показват се с плаващите бутони върху него.
 *
 * Всеки отворен таб тръгва със скрити ленти, както и да е оставен предишният: при отваряне
 * се гледа терминалът, а клавиатурата не бива да закрива половината от него.
 * Състоянието живее във view model-а на таба, затова завъртането не го губи.
 */
data class TerminalBars(
  val topBar: Boolean = false,
  val input: Boolean = false,
)
